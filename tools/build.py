"""Builds the two deliverables of CHT Drift Judge from app/CHT_DriftJudge:

  online/cht_drift_judge.lua        – one file for the server (CSP online script, linked from the server's
                                      csp_extra_options.ini [SCRIPT_…] section via GitHub raw)
  dist/CHT_DriftJudge_v<ver>.zip    – the installed Lua app (apps/lua/CHT_DriftJudge + OLVASS_EL.txt)

Run: python3 tools/build.py
"""
import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, 'app', 'CHT_DriftJudge')
MAIN = os.path.join(APP, 'CHT_DriftJudge.lua')


def app_version():
    m = re.search(r"local APP_VERSION = '([^']+)'", open(MAIN, encoding='utf-8').read())
    if not m:
        sys.exit('APP_VERSION not found')
    return m.group(1)


def modules():
    src = os.path.join(APP, 'src')
    names = sorted(f for f in os.listdir(src) if f.endswith('.lua'))
    return [('src/' + f[:-4], open(os.path.join(src, f), encoding='utf-8').read()) for f in names]


def bundle(version):
    out = [
        f'-- CHT Drift Judge {version} – online script for the server (generated by tools/build.py: do not edit).',
        '-- Source: https://github.com/martondavid04-design/cht-drift-judge (app/CHT_DriftJudge).',
        '-- Server: csp_extra_options.ini → [SCRIPT_1] SCRIPT = <raw link of this file>.',
        '__CHT_ONLINE__ = true',
        f"__CHT_BUNDLE_VERSION__ = '{version}'",
        'local __modules, __loaded = {}, {}',
        'local __require = require',
        'local function require(name)',
        '  local v = __loaded[name]',
        '  if v ~= nil then return v end',
        '  local f = __modules[name]',
        '  if f then',
        '    v = f(name)',
        '    if v == nil then v = true end',
        '    __loaded[name] = v',
        '    return v',
        '  end',
        '  return __require(name)',
        'end',
        "if rawget(_G, '__STUB') then __CHT_REQUIRE__ = require end -- offline tests only",
        '',
    ]
    for name, code in modules():
        if '\n#!' in code[:3]:
            code = code.split('\n', 1)[1]
        out.append(f"__modules['{name}'] = function(...)")
        out.append(code.rstrip('\n'))
        out.append('end')
        out.append('')
    out.append('-- main script ---------------------------------------------------------------------------------')
    out.append(open(MAIN, encoding='utf-8').read().rstrip('\n'))
    out.append('')
    return '\n'.join(out)


def check_lua(text, name):
    try:
        from lupa import luajit21 as lj
    except ImportError:
        print('(lupa not installed: syntax check skipped)')
        return
    L = lj.LuaRuntime()
    chk = L.eval('function(s, n) local f, e = loadstring(s, n); return e or "ok" end')
    r = chk(text, name)
    if r != 'ok':
        sys.exit(f'Lua syntax error in {name}: {r}')


def build_zip(version):
    os.makedirs(os.path.join(ROOT, 'dist'), exist_ok=True)
    path = os.path.join(ROOT, 'dist', f'CHT_DriftJudge_v{version}.zip')
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        for base, _, files in os.walk(APP):
            for f in sorted(files):
                if f.endswith(('.orig', '~')) or f.startswith('.'):
                    continue
                full = os.path.join(base, f)
                rel = os.path.relpath(full, APP).replace(os.sep, '/')
                z.write(full, 'apps/lua/CHT_DriftJudge/' + rel)
        z.write(os.path.join(ROOT, 'OLVASS_EL.txt'), 'OLVASS_EL.txt')
    return path


def main():
    version = app_version()
    manifest = open(os.path.join(APP, 'manifest.ini'), encoding='utf-8').read()
    if f'VERSION = {version}' not in manifest:
        sys.exit(f'manifest.ini VERSION is not {version}')
    for name, code in modules():
        check_lua(code, name)
    check_lua(open(MAIN, encoding='utf-8').read(), 'CHT_DriftJudge.lua')
    text = bundle(version)
    check_lua(text, 'cht_drift_judge.lua')
    os.makedirs(os.path.join(ROOT, 'online'), exist_ok=True)
    out = os.path.join(ROOT, 'online', 'cht_drift_judge.lua')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    z = build_zip(version)
    print(f'version {version}')
    print(f'online bundle: {out} ({len(text.encode("utf-8")) // 1024} KB)')
    print(f'app package:   {z}')


if __name__ == '__main__':
    main()
